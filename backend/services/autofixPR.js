// ── Slug generator ────────────────────────────────────────────────────────
function createSlug(text) {
    return (text || 'unknown-error')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '')
        .substring(0, 40);
}
