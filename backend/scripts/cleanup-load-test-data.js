import mongoose from 'mongoose';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

dotenv.config({ path: path.resolve(__dirname, '../.env') });

const MONGO_URI = process.env.MONGODB_URI;
if (!MONGO_URI) {
    console.error('❌ MONGODB_URI is not defined in .env');
    process.exit(1);
}

import User from '../models/User.js';
import Brand from '../models/Brand.js';
import Creative from '../models/Creative.js';
import Content from '../models/Content.js';
import PulseHistory from '../models/PulseHistory.js';
import BrainstormSession from '../models/BrainstormSession.js';
import ActivityLog from '../models/ActivityLog.js';
import GenerationJob from '../models/GenerationJob.js';
import Product from '../models/Product.js';
import SeoAudit from '../models/SeoAudit.js';
import YoutubeProject from '../models/YoutubeProject.js';

async function run() {
    try {
        await mongoose.connect(MONGO_URI);
        console.log('✅ Connected to MongoDB.');

        const user = await User.findOne({ email: 'user@mantram.ai' });
        if (!user) {
            console.log('❌ User user@mantram.ai not found. Nothing to clean up.');
            return;
        }

        const userId = user._id;
        console.log(`🧹 Cleaning up data generated by user ${user.email} (${userId})...`);

        // Delete Brands
        const delBrands = await Brand.deleteMany({ user: userId });
        console.log(`   🗑️ Deleted ${delBrands.deletedCount} Brand documents.`);

        // Delete Products
        const delProducts = await Product.deleteMany({ brand: { $exists: false } }); // clean orphan products if any
        console.log(`   🗑️ Deleted ${delProducts.deletedCount} orphan Product documents.`);

        // Delete Creatives
        const delCreatives = await Creative.deleteMany({ user: userId });
        console.log(`   🗑️ Deleted ${delCreatives.deletedCount} Creative documents.`);

        // Delete Content
        const delContent = await Content.deleteMany({ user: userId });
        console.log(`   🗑️ Deleted ${delContent.deletedCount} Content documents.`);

        // Delete Pulse Histories
        const delPulse = await PulseHistory.deleteMany({ user: userId });
        console.log(`   🗑️ Deleted ${delPulse.deletedCount} PulseHistory documents.`);

        // Delete Brainstorm Sessions
        const delBrainstorm = await BrainstormSession.deleteMany({ user: userId });
        console.log(`   🗑️ Deleted ${delBrainstorm.deletedCount} BrainstormSession documents.`);

        // Delete Activity Logs
        const delLogs = await ActivityLog.deleteMany({ user: userId });
        console.log(`   🗑️ Deleted ${delLogs.deletedCount} ActivityLog documents.`);

        // Delete Generation Jobs
        const delJobs = await GenerationJob.deleteMany({ user: userId });
        console.log(`   🗑️ Deleted ${delJobs.deletedCount} GenerationJob documents.`);

        // Delete SEO Audits
        const delSeo = await SeoAudit.deleteMany({ user: userId });
        console.log(`   🗑️ Deleted ${delSeo.deletedCount} SeoAudit documents.`);

        // Delete YouTube Projects
        const delYt = await YoutubeProject.deleteMany({ userId: userId });
        console.log(`   🗑️ Deleted ${delYt.deletedCount} YoutubeProject documents.`);

        // Restore credits of user@mantram.ai back to 100
        await User.updateOne(
            { _id: userId },
            { $set: { 'credits.total': 100, 'credits.used': -145, 'credits.bonus': 142, 'credits.topUp': 0 } }
        );
        console.log('🔄 Restored credits of user@mantram.ai back to original values.');

        console.log('✅ Cleanup complete. Database is clean.');
    } catch (err) {
        console.error('❌ Error during cleanup:', err);
    } finally {
        await mongoose.disconnect();
    }
}

run();
